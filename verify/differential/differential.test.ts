test("admitReport rejects any failing verdict and requires full accounting", () => {
  const base: Report = {
    contract: "algal.differential-report.v1", seeds: [1], cases: 3, mode: "inline",
    artifacts: { wasm: { path: "/w", sha256: "sha256:" + "0".repeat(64), bytes: 1 }, native: null, bun: { path: "/b", sha256: "sha256:" + "0".repeat(64), bytes: 1 } },
    verdicts: { agree: 2, uncovered: 1 }, oracle: { exact: 3, uncovered: 0 },
    coverage: { ops: [], codes: {}, notes: [] }, mismatches: [], elapsedMs: 0,
  };
  expect(() => admitReport(base)).not.toThrow();
  expect(() => admitReport({ ...base, verdicts: { agree: 2 } })).toThrow("cover every case");
  expect(() => admitReport({ ...base, verdicts: { agree: 3, "infra-failure": 1 }, cases: 4 })).toThrow("failures or mismatches");
  expect(() => admitReport({ ...base, cases: 0 })).toThrow("case bound");
});
