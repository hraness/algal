// -------------------------------------------------------------- engine ----

const RESP_OK = '{"fuel":4,"ok":true,"value":3}';
const RESP_ERR = '{"err":{"code":"EXPR_FUEL","what":"fuel"},"fuel":3,"ok":false}';

test("classifyResponse separates ok/error/malformed response classes", () => {
  expect(classifyResponse("eval", RESP_OK)).toEqual({ cls: "ok:fuel=4", canonical: "3" });
  expect(classifyResponse("eval", RESP_ERR)).toEqual({ cls: "err:EXPR_FUEL:fuel=3", canonical: null });
  expect(classifyResponse("eval", "garbage").cls).toBe("malformed");
  expect(classifyResponse("eval", '{"ok":true,"value":1}').cls).toBe("malformed"); // missing fuel
  expect(classifyResponse("check", '{"ok":true}')).toEqual({ cls: "ok", canonical: null });
  expect(classifyResponse("check", '{"err":{"code":"EXPR_PATH"},"ok":false}')).toEqual({ cls: "err:EXPR_PATH", canonical: null });
  expect(classifyResponse("check", '{"ok":true,"extra":1}').cls).toBe("ok"); // extra detail fields are tolerated
});

test("compareCase verdicts: agreement, oracle divergence, target divergence, wrapper divergence, transport, infra", () => {
  const bytes = enc.encode('{"program":["add",1,2],"fuel":100}');
  const okResp = JSON.stringify({ fuel: 4, ok: true, value: 3 });
  expect(compareCase("eval", bytes, { status: "ok", text: okResp }, { status: "ok", text: okResp }, { fuel: 4, ok: true, value: 3 }).verdict).toBe("agree");
  // oracle divergence: wasm claims fuel 5 for a 4-cost program
  expect(compareCase("eval", bytes, { status: "ok", text: '{"fuel":5,"ok":true,"value":3}' }, null, "skipped").verdict).toBe("mismatch-oracle");
  // target divergence: native bytes differ from wasm bytes
  const target = compareCase("eval", bytes, { status: "ok", text: okResp }, { status: "ok", text: '{"fuel":4,"ok":true,"value":3.0}' }, "skipped");
  expect(target.verdict === "mismatch-targets" || target.verdict === "agree").toBe(true); // identical text would agree; different bytes must not
  expect(compareCase("eval", bytes, { status: "ok", text: okResp }, { status: "ok", text: RESP_ERR }, "skipped").verdict).toBe("mismatch-targets");
  // wrapper divergence: wrapper result differs from raw boundary object
  expect(compareCase("eval", bytes, { status: "ok", text: okResp }, null, { fuel: 4, ok: true, value: 4 }).verdict).toBe("mismatch-wrapper");
  // transport and infrastructure classes
  expect(compareCase("eval", bytes, { status: "null-input", error: "x" }, null, "skipped").verdict).toBe("wasm-transport");
  expect(compareCase("eval", bytes, { status: "trap", error: "x" }, null, "skipped").verdict).toBe("infra-failure");
  expect(compareCase("eval", bytes, { status: "ok", text: "not-json" }, null, "skipped").verdict).toBe("infra-failure");
  expect(compareCase("eval", bytes, { status: "ok", text: okResp }, { status: "timeout", error: "d" }, "skipped").verdict).toBe("infra-failure");
  // wrapper threw is recorded, not hidden
  const threw = compareCase("eval", bytes, { status: "ok", text: okResp }, null, { threw: "boom" });
  expect(threw.wrapperClass?.startsWith("wrapper-threw:")).toBe(true);
});

test("wrapperFaithful admits only envelopes whose fuel token survives JSON.stringify", () => {
  expect(wrapperFaithful(enc.encode('{"program":true}'))).toBe(true);
  expect(wrapperFaithful(enc.encode('{"program":true,"fuel":5}'))).toBe(true);
  expect(wrapperFaithful(enc.encode('{"program":true,"fuel":5.0}'))).toBe(false);  // 5.0 re-encodes as 5 — different admission
  expect(wrapperFaithful(enc.encode('{"program":true,"fuel":-1}'))).toBe(false);   // -1 loses its u64 refusal
  expect(wrapperFaithful(enc.encode('{"program":true,"fuel":"x"}'))).toBe(true);   // non-number fuel rejects identically
  expect(wrapperFaithful(enc.encode('not json'))).toBe(false);
});

// -------------------------------------------------------------- shrink ----

test("shrinkBytes reduces a reproducing input and reconfirms the result", async () => {
  const original = enc.encode('{"program":["add",["sub",5,["get","x"]],{"a":[1,2,3]}],"env":{"x":0}}');
  let calls = 0;
  const reproduces = async (c: Uint8Array): Promise<boolean> => {
    calls++;
    const p = parseJsonBytes(c);
    return p.ok && p.value instanceof Map && p.value.has("program");
  };
  const out = await shrinkBytes(original, reproduces, { attempts: 40, deadlineMs: 5000 });
  expect(out.bytes.byteLength).toBeLessThan(original.byteLength);
  expect(out.attempts).toBe(calls);
  expect(parseJsonBytes(out.bytes).ok).toBe(true);
});

test("shrinkBytes honors the attempt bound and refuses a non-reproducing seed", async () => {
  const original = enc.encode('{"program":["add",1,{"a":2},{"b":[3,4]}]}');
  let calls = 0;
  const out = await shrinkBytes(original, async () => { calls++; return false; }, { attempts: 7, deadlineMs: 5000 }).catch(e => e);
  // The seed itself does not reproduce — the loop must fail loudly, not return it.
  expect(String(out)).toContain("did not reproduce");
  const trimmed = await shrinkBytes(original, async c => { calls++; return c.byteLength > 20; }, { attempts: 100, deadlineMs: 5000 });
  expect(trimmed.bytes.byteLength).toBeGreaterThanOrEqual(21);
  expect(calls).toBeGreaterThan(0);
  const first = [...candidates(original)];
  expect(first.length).toBeGreaterThan(10);
  expect(first.every(c => c.byteLength <= original.byteLength)).toBe(true);
});

