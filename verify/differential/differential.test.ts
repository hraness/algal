test("oracle predicts full canonical response including spent fuel", () => {
  const r = predictEval(enc.encode('{"program":["add",1,2],"fuel":100}'));
  expect(r).toEqual({ ok: true, value: { kind: "num", f64: 3, u64: null }, fuel: 4 });
  const fuelErr = predictEval(enc.encode('{"program":["add",1,2],"fuel":3}'));
  expect(fuelErr).toEqual({ ok: false, code: "EXPR_FUEL", fuel: 3 });
  const parse = predictEval(enc.encode("not json"));
  expect(parse).toEqual({ ok: false, code: "EXPR_PARSE", fuel: 0 });
  const noProgram = predictEval(enc.encode('{"env":{"x":1}}'));
  expect(noProgram).toEqual({ ok: false, code: "EXPR_PARSE", fuel: 0 });
  // fuel spelling: u64 typed integers admit; float-typed or out-of-range reject as bounds.
  expect(predictEval(enc.encode('{"program":true,"fuel":5}'))).toEqual({ ok: true, value: true, fuel: 1 });
  expect(predictEval(enc.encode('{"program":true,"fuel":100.0}')).ok).toBe(false);
  expect(predictEval(enc.encode('{"program":true,"fuel":1000001}')).ok).toBe(false);
  expect(predictCheck(enc.encode('{"program":["get","x"],"names":["x"]}'))).toEqual({ ok: true });
  expect(predictCheck(enc.encode('{"program":["get","x"],"names":[]}'))).toEqual({ ok: false, code: "EXPR_PATH" });
});

