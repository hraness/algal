test("committed wasm boundary answers a real envelope (in-process leg)", async () => {
  const mod = await loadWasmModule(WASM);
  const text = callRaw(mod, "algal_eval", enc.encode('{"program":["add",1,2],"fuel":100}'));
  expect(JSON.parse(text)).toEqual({ fuel: 4, ok: true, value: 3 });
  const chk = callRaw(mod, "algal_check", enc.encode('{"program":["get","x"],"names":["x"]}'));
  expect(JSON.parse(chk)).toEqual({ ok: true });
  // A trap/parse rejection is a shaped response, not a transport fault.
  const bad = callRaw(mod, "algal_eval", enc.encode("not json"));
  expect(JSON.parse(bad).ok).toBe(false);
});

test("worker manifest: per-case lines, zero-byte transport admission, read errors", async () => {
  const dir = await mkdtemp(join(tmpdir(), "diff-worker-"));
  await writeFile(join(dir, "a.bin"), enc.encode('{"program":true}'));
  await writeFile(join(dir, "b.bin"), enc.encode('{"program":["get","x"],"names":["x"]}'));
  await writeFile(join(dir, "empty.bin"), new Uint8Array(0));
  const manifestPath = join(dir, "m.json");
  await writeFile(manifestPath, JSON.stringify({
    wasm: WASM,
    cases: [
      { id: "a", path: join(dir, "a.bin"), mode: "eval", wrapper: true },
      { id: "b", path: join(dir, "b.bin"), mode: "check", wrapper: true },
      { id: "empty", path: join(dir, "empty.bin"), mode: "eval", wrapper: false },
      { id: "gone", path: join(dir, "gone.bin"), mode: "eval", wrapper: false },
    ],
  }));
  const lines = await runWorkerManifest(manifestPath);
  expect(lines).toHaveLength(4);
  expect(lines[0]).toMatchObject({ id: "a", wasm: { status: "ok" } });
  expect(lines[0]!.wrapper).toEqual({ fuel: 1, ok: true, value: true });
  expect(lines[1]).toMatchObject({ id: "b", wasm: { status: "ok" } });
  expect(lines[2]!.wasm.status).toBe("null-input");
  expect(lines[3]!.wasm.status).toBe("read-error");
});

// -------------------------------------------------------------- driver ----

test("inline differential run: all verdicts account for every case, oracle exact", async () => {
  const archiveDir = await mkdtemp(join(tmpdir(), "diff-run-"));
  const report = await runDifferential({
    root: join(import.meta.dir, "../.."),
    wasm: WASM,
    ...(NATIVE !== undefined ? { native: NATIVE } : {}),
    seeds: [1],
    archiveDir,
    mode: "inline",
  });
  expect(report.contract).toBe("algal.differential-report.v1");
  const total = Object.values(report.verdicts).reduce((a, b) => a + b, 0);
  expect(total).toBe(report.cases);
  expect(report.mismatches).toHaveLength(0);
  expect(report.oracle.exact).toBe(report.cases);
  expect(report.verdicts["infra-failure"]).toBeUndefined();
  expect(report.verdicts["mismatch-oracle"]).toBeUndefined();
  expect(report.verdicts["mismatch-targets"]).toBeUndefined();
  expect(report.coverage.ops.length).toBeGreaterThan(40);
  expect(report.artifacts.wasm.sha256).toMatch(/^sha256:[a-f0-9]{64}$/);
  admitReport(report as Report);
}, 120_000);

