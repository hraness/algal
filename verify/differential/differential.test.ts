// ------------------------------------------------------------ catalog -----

test("catalog is deterministic, uniquely identified, bounded and modal", () => {
  const a = catalog(DEFAULT_SEEDS), b = catalog(DEFAULT_SEEDS);
  expect(a.length).toBe(b.length);
  expect(a.map(c => c.id)).toEqual(b.map(c => c.id));
  for (let i = 0; i < a.length; i++) expect(Buffer.from(a[i]!.bytes).toString("base64")).toBe(Buffer.from(b[i]!.bytes).toString("base64"));
  expect(new Set(a.map(c => c.id)).size).toBe(a.length);
  expect(a.length).toBeGreaterThan(300);
  expect(a.length).toBeLessThanOrEqual(LIMITS.cases);
  for (const c of a) {
    expect(c.bytes.byteLength).toBeLessThanOrEqual(LIMITS.inputBytes);
    expect(c.mode === "eval" || c.mode === "check").toBe(true);
    expect(/^[a-z0-9._-]+$/i.test(c.id)).toBe(true); // worker filename admission
  }
  expect(a.filter(c => c.mode === "check").length).toBeGreaterThan(15);
  expect(a.filter(c => c.id.startsWith("gen-")).length).toBe(4 * 60);
  expect(a.filter(c => c.wrapper).length).toBeGreaterThan(50);
  // Different seed streams produce different generated bytes.
  const alt = catalog([0xdead]);
  expect(alt.some(c => c.id.startsWith("gen-dead-"))).toBe(true);
});

// ------------------------------------------------------------- json.rs ----

test("independent parser: byte admission edges", () => {
  expect(parseJsonBytes(enc.encode("")).ok).toBe(false);
  expect(parseJsonBytes(enc.encode("  \t\n\r ")).ok).toBe(false);
  expect(parseJsonBytes(enc.encode("null")).ok).toBe(true);
  expect(parseJsonBytes(enc.encode("null ")).ok).toBe(true);
  expect(parseJsonBytes(enc.encode("null x")).ok).toBe(false);
  expect(parseJsonBytes(enc.encode("﻿null")).ok).toBe(false); // BOM rejects
  expect(parseJsonBytes(enc.encode('{"a":1,"a":2}')).ok).toBe(true);
  const dup = parseJsonBytes(enc.encode('{"a":1,"a":2}'));
  expect(dup.ok && dup.value instanceof Map && dup.value.get("a")).toEqual({ kind: "num", f64: 2, u64: 2n });
  // Invalid UTF-8 and lone surrogates reject; valid astral pairs admit.
  expect(parseJsonBytes(Uint8Array.from([0x22, 0xed, 0xa0, 0x80, 0x22])).ok).toBe(false);
  expect(parseJsonBytes(Uint8Array.from([0x22, 0x80, 0x22])).ok).toBe(false);
  expect(parseJsonBytes(enc.encode('"\\ud800"')).ok).toBe(false);
  expect(parseJsonBytes(enc.encode('"\\udc00"')).ok).toBe(false);
  expect(parseJsonBytes(enc.encode('"\\ud83d\\ude00"')).ok).toBe(true);
  expect(parseJsonBytes(enc.encode('"\\ud800\\ud800"')).ok).toBe(false);
  expect(parseJsonBytes(Uint8Array.from([0x22, 0x00, 0x22])).ok).toBe(false); // raw control
  expect(parseJsonBytes(Uint8Array.from([0x22, 0x7f, 0x22])).ok).toBe(true);  // DEL is data
});

test("independent parser: number domain boundaries", () => {
  const numAt = (t: string): JVal => {
    const r = parseJsonBytes(enc.encode(t));
    if (!r.ok) throw r.error;
    return r.value;
  };
  expect(numAt("18446744073709551615")).toEqual({ kind: "num", f64: Number("18446744073709551615"), u64: 18446744073709551615n });
  expect((numAt("18446744073709551616") as { u64: bigint | null }).u64).toBe(null); // falls back to f64
  expect((numAt("-9223372036854775808") as { f64: number }).f64).toBe(-(2 ** 63));
  expect(numAt("5e-324")).toEqual({ kind: "num", f64: 5e-324, u64: null });
  expect(parseJsonBytes(enc.encode("1e309")).ok).toBe(false);   // non-finite rejects
  expect(parseJsonBytes(enc.encode("01")).ok).toBe(false);
  expect(parseJsonBytes(enc.encode("+1")).ok).toBe(false);
  expect(parseJsonBytes(enc.encode("1.")).ok).toBe(false);
  expect(numAt("1e2")).toEqual({ kind: "num", f64: 100, u64: null }); // exponent spelling is f64-typed
  const neg0 = numAt("-0") as { f64: number; u64: bigint | null };
  expect(Object.is(neg0.f64, -0)).toBe(true);
});

test("independent parser: container depth boundary 127/128", () => {
  const deep = (n: number) => enc.encode("[".repeat(n) + "1" + "]".repeat(n));
  expect(parseJsonBytes(deep(JSON_CONTAINER_DEPTH_MAX)).ok).toBe(true);
  expect(parseJsonBytes(deep(JSON_CONTAINER_DEPTH_MAX + 1)).ok).toBe(false);
});

// --------------------------------------------------------- canonical ------

test("canonical key order: array indices numerically first, then UTF-16 units", () => {
  const m = new Map<string, JVal>();
  for (const k of ["z", "10", "￿", "𐀀", "2", "01", "4294967296", "4294967295", "4294967294", "a", "A", "0"]) m.set(k, num(0));
  const text = canonical(m);
  const order = [...text.matchAll(/"((?:[^"\\]|\\.)*)":/g)].map(x => JSON.parse(`"${x[1]}"`));
  // Index keys (u32, canonical spelling, < 2^32-1) numerically first — note
  // 4294967295 is u32::MAX and is NOT an index key. Remaining keys sort by
  // UTF-16 code units, where 𐀀 (U+10000 → D800 DC00) precedes ￿ (U+FFFF) —
  // the opposite of UTF-8/scalar order. Both facts are pinned deliberately.
  expect(order).toEqual(["0", "2", "10", "4294967294", "01", "4294967295", "4294967296", "A", "a", "z", "𐀀", "￿"]);
  expect(keyOrder("2", "10")).toBeLessThan(0);
  expect(keyOrder("4294967294", "01")).toBeLessThan(0); // 4294967294 is a u32 index; "01" is not
  expect(keyOrder("4294967295", "0")).toBeGreaterThan(0); // u32::MAX sorts as a plain string
  expect(keyOrder("𐀀", "￿")).toBeLessThan(0); // UTF-16 units; scalar order disagrees
});

test("structural mirrors: node count, depth and canonical byte accounting", () => {
  const v: JVal = new Map<string, JVal>([["b", [num(1), num(2)]], ["a", num(0)]]);
  expect(countNodes(v)).toBe(5);
  expect(valueDepth(v)).toBe(2);
  expect(canonical(v)).toBe('{"a":0,"b":[1,2]}');
  expect(canonicalBytes(v)).toBe(17);
  expect(() => valueBytes(Array.from({ length: BOUNDS.maxListLen + 1 }, () => num(0)), 0)).toThrow(Bounds);
  let deep: JVal = num(0);
  for (let i = 0; i < BOUNDS.maxValueDepth + 1; i++) deep = [deep];
  expect(() => valueBytes(deep, 0)).toThrow(Bounds);
  expect(() => valueBytes("x".repeat(BOUNDS.maxStringBytes + 1), 0)).toThrow(Bounds);
});

